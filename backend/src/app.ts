import express from 'express';
import cors from 'cors';
import { env } from './config/env.js';
import { authRouter } from './routes/auth.js';
import { projectsRouter } from './routes/projects.js';
import { jobsRouter } from './routes/jobs.js';
import { catalogRouter } from './routes/catalog.js';
import { analyticsRouter } from './routes/analytics.js';
import { auditRouter } from './routes/audit.js';
import { billingRouter, resultsRouter } from './routes/billing.js';
import { ingestRouter, monitoringRouter, schedulerRouter } from './routes/monitoring.js';
import { errorHandler } from './middleware/errors.js';

export const app=express();
app.disable('x-powered-by');
app.use(cors({origin:env.WEB_ORIGIN,credentials:false}));
app.use(express.json({limit:'1mb'}));
app.get('/api/health',(_req,res)=>res.json({status:'ok'}));
app.use('/api/auth',authRouter);
app.use('/api/projects',projectsRouter);
app.use('/api/jobs',jobsRouter);
app.use('/api',catalogRouter);
app.use('/api/analytics',analyticsRouter);
app.use('/api/audit',auditRouter);
app.use('/api',billingRouter);
app.use('/api',resultsRouter);
app.use('/api/monitoring',monitoringRouter);
app.use('/api/search',monitoringRouter);
app.use('/api/ingest',ingestRouter);
app.use('/api/scheduler',schedulerRouter);
app.use((_req,res)=>res.status(404).json({error:{code:'ROUTE_NOT_FOUND',message:'API route not found.'}}));
app.use(errorHandler);
